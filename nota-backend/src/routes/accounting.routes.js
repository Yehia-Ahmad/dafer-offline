const express = require("express");
const { requirePermission, requireLogin } = require("../auth/middleware");
const asyncHandler = require("../utils/asyncHandler");
const controller = require("../controllers/accounting.controller");
const manualEntries = require("../controllers/manualEntry.controller");
const accountAdmin = require("../controllers/accountAdmin.controller");
const closingController = require("../controllers/closing.controller");
const router = express.Router();
router.get("/accounts", requirePermission("accounting.view"), asyncHandler(controller.getAccounts));
router.get("/accounts/next-code", requirePermission("accounting.manage"), asyncHandler(accountAdmin.getNextCode));
router.post("/accounts", requirePermission("accounting.manage"), asyncHandler(accountAdmin.createAccount));
router.get("/accounts/:id/ledger", requirePermission("accounting.view"), asyncHandler(controller.getLedger));
router.get("/accounts/:id/usage", requirePermission("accounting.manage"), asyncHandler(accountAdmin.getUsage));
router.put("/accounts/:id", requirePermission("accounting.manage"), asyncHandler(accountAdmin.updateAccount));
router.post("/accounts/:id/deactivate", requirePermission("accounting.manage"), asyncHandler(accountAdmin.deactivateAccount));
router.post("/accounts/:id/reactivate", requirePermission("accounting.manage"), asyncHandler(accountAdmin.reactivateAccount));
router.delete("/accounts/:id", requirePermission("accounting.manage"), asyncHandler(accountAdmin.deleteAccount));
router.get("/manual-entries/accounts", requirePermission("accounting.manage"), asyncHandler(manualEntries.getAccountOptions));
router.get("/manual-entries", requirePermission("accounting.manage"), asyncHandler(manualEntries.listEntries));
router.post("/manual-entries", requirePermission("accounting.manage"), asyncHandler(manualEntries.createDraft));
router.get("/manual-entries/:id", requirePermission("accounting.manage"), asyncHandler(manualEntries.getEntry));
router.put("/manual-entries/:id", requirePermission("accounting.manage"), asyncHandler(manualEntries.updateDraft));
router.delete("/manual-entries/:id", requirePermission("accounting.manage"), asyncHandler(manualEntries.deleteDraft));
router.post("/manual-entries/:id/post", requirePermission("accounting.manage"), asyncHandler(manualEntries.postEntry));
router.post("/manual-entries/:id/reverse", requirePermission("accounting.manage"), asyncHandler(manualEntries.reverseEntry));
router.get("/journal", requirePermission("accounting.view"), asyncHandler(controller.getJournal));
router.get("/journal/:id", requirePermission("accounting.view"), asyncHandler(controller.getJournalEntry));
router.get("/opening", requirePermission("accounting.view"), asyncHandler(controller.getOpening));
router.post("/opening", requirePermission("accounting.manage"), asyncHandler(controller.saveOpening));
router.post("/opening/finalize", requirePermission("accounting.manage"), asyncHandler(controller.finalizeOpening));
router.get("/health", requirePermission("accounting.view"), asyncHandler(controller.getHealth));
router.get("/lock-date", requireLogin(), asyncHandler(closingController.getLockDate));
router.get("/closing", requirePermission("accounting.view"), asyncHandler(closingController.getClosing));
router.post("/closing/close", requirePermission("accounting.close"), asyncHandler(closingController.closePeriod));
router.post("/closing/reopen", requirePermission("accounting.close"), asyncHandler(closingController.reopenPeriod));
module.exports = router;
