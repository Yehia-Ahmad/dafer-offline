// Online Stage Help: the whole help as one Markdown file (docs/help/HELP_AR.md), for reviewing the text in one place.
// The same function runs in scripts/export-help.mjs (writes the file) and in help-export.spec.ts (checks it is up to date).
import type { RouteRule } from '../core/auth/route-permissions';
import { HELP_PART_TITLES, HelpBlock, HelpSection } from './help.models';
import { parseInline } from './inline-parse';

export interface MarkdownContext {
  sections: readonly HelpSection[];
  /** Arabic label of a permission key. */
  permissionLabel: (key: string) => string;
}

const cell = (value: string) => value.replace(/\|/g, '\\|').replace(/\n/g, ' ');
/** 1234.5 → "1,234.50" without Intl (the script and the browser must produce the same bytes). */
export const money = (value: number | undefined) => {
  if (value === undefined) return '';
  const [whole, fraction] = value.toFixed(2).split('.');
  return `${whole.replace(/\B(?=(\d{3})+(?!\d))/g, ',')}.${fraction}`;
};

export function ruleText(rule: RouteRule | undefined, label: (key: string) => string): string {
  if (!rule) return 'كل المستخدمين';
  const parts: string[] = [];
  if (rule.all?.length) parts.push(rule.all.map(label).join(' + '));
  if (rule.any?.length) parts.push(rule.any.map(label).join(' أو '));
  return parts.join(' + ');
}

function inline(source: string, ctx: MarkdownContext): string {
  return parseInline(source).map((token) => {
    switch (token.kind) {
      case 'text': return token.text;
      case 'bold': return `**${token.text}**`;
      case 'page': return `${token.text} (\`${token.route}\`)`;
      case 'section': {
        const target = ctx.sections.find((section) => section.id === token.id);
        return `${token.text} (← ${target?.title ?? token.id})`;
      }
    }
  }).join('');
}

function table(head: string[], rows: string[][], ctx: MarkdownContext): string[] {
  return [
    `| ${head.map((value) => cell(inline(value, ctx))).join(' | ')} |`,
    `|${head.map(() => '---').join('|')}|`,
    ...rows.map((row) => `| ${head.map((_, index) => cell(inline(row[index] ?? '', ctx))).join(' | ')} |`),
  ];
}

function block(item: HelpBlock, ctx: MarkdownContext): string[] {
  const md = (value: string) => inline(value, ctx);
  const titled = (title: string | undefined) => (title ? [`**${md(title)}**`, ''] : []);
  switch (item.type) {
    case 'heading': return [`### ${md(item.text || (item.part ? HELP_PART_TITLES[item.part] : ''))}`];
    case 'paragraph': return [md(item.text)];
    case 'tip': return [`> 💡 ${md(item.text)}`];
    case 'warning': return [`> ⚠️ ${md(item.text)}`];
    case 'steps': return [`**${md(item.title)}**`, '', ...item.items.map((step, index) => `${index + 1}. ${md(step)}`)];
    case 'bullets': return [...titled(item.title), ...item.items.map((line) => `- ${md(line)}`)];
    case 'behind': return [
      `**${md(item.title)}**`, '',
      ...item.text.map((line) => `- ${md(line)}`),
      ...(item.entry?.length ? ['', ...table(['الحساب', 'مدين', 'دائن'], item.entry.map((line) => [line.account, money(line.debit), money(line.credit)]), ctx)] : []),
    ];
    case 'fields': return [...titled(item.title), ...table(['الخانة', 'معناها', 'القواعد'], item.rows.map((row) => [row.field, row.meaning, row.rules ?? '']), ctx)];
    case 'actions': return [...titled(item.title), ...table(['الزرار', 'بيعمل إيه', 'إمتى مش هتلاقيه / مقفول'], item.rows.map((row) => [row.action, row.does, row.when ?? '']), ctx)];
    case 'statuses': return [...titled(item.title), ...table(['الحالة', 'معناها', 'تقدر تعمل إيه'], item.rows.map((row) => [row.status, row.meaning, row.next ?? '']), ctx)];
    case 'blockers': return [...titled(item.title), ...table(['اللي بيمنعك', 'تعمل إيه'], item.rows.map((row) => [row.rule, row.fix]), ctx)];
    case 'faq': return item.items.flatMap((faq) => [`**س: ${md(faq.q)}**`, '', `ج: ${md(faq.a)}`, '']).slice(0, -1);
    case 'table': return [...titled(item.title), ...table([...item.head], item.rows, ctx)];
  }
}

export function helpToMarkdown(ctx: MarkdownContext): string {
  const lines: string[] = [
    '<!-- Generated by nota-frontend/scripts/export-help.mjs from src/app/help/content. Do not edit by hand. -->',
    '',
    '# مساعدة نوتة',
    '',
    ...ctx.sections.map((section, index) => `${index + 1}. ${section.title}`),
    '',
  ];
  for (const section of ctx.sections) {
    lines.push(`## ${section.title}`, '');
    lines.push(`_${inline(section.summary, ctx)}_`, '');
    lines.push(`- المعرّف: \`${section.id}\``);
    lines.push(`- الصفحات: ${section.routes.length ? section.routes.map((route) => `\`/${route}\``).join('، ') : '—'}`);
    lines.push(`- مين يشوفه: ${ruleText(section.permissions, ctx.permissionLabel)}`);
    if (section.related.length) {
      lines.push(`- أقسام مرتبطة: ${section.related.map((id) => ctx.sections.find((s) => s.id === id)?.title ?? id).join('، ')}`);
    }
    lines.push('');
    for (const item of section.blocks) lines.push(...block(item, ctx), '');
  }
  return lines.join('\n').replace(/\n{3,}/g, '\n\n').trimEnd() + '\n';
}
