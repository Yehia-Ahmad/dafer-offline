const roleNames = PERMISSION_CATALOG.roles;
const holders = (key: string) => ['owner', 'manager', 'cashier', 'storekeeper', 'accountant']
  .filter((role) => (PERMISSION_CATALOG.templates[role] ?? []).includes(key))
  .map((role) => roleNames[role] ?? role)
  .join('، ');

/** One row per catalog permission, in catalog order: label, what it allows, which role templates have it. */
const permissionRows: string[][] = PERMISSION_CATALOG.keys.map((key) => {
  const entry = PERMISSION_CATALOG.permissions[key];
  const group = PERMISSION_CATALOG.groups[entry.group] ?? entry.group;
  const needs = (PERMISSION_CATALOG.dependencies[key] ?? []).map((dep) => PERMISSION_CATALOG.permissions[dep]?.ar ?? dep);
  const allows = `${PERMISSION_HELP[key] ?? ''}${needs.length ? ` (محتاجة: ${needs.join('، ')})` : ''}`;
  return [`**${entry.ar}** — ${group}`, allows, holders(key) || '—'];
});

