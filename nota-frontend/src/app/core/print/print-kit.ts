const PAGE_RULES: Record<PrintPaper, string> = {
  A4: '@page { size: A4; margin: 10.5mm 10.5mm 16mm 10.5mm; }',
  A5: '@page { size: A5; margin: 10.5mm; }',
  '80mm': '@page { size: 80mm var(--roll-height, 297mm); margin: 0; }',
};

/** The page-number and "printed by" boxes in the bottom margin of every page (Chromium honors @page margin boxes). */
function marginBoxes(ctx: PrintContext, doc: PrintDocument): string {
  const rtl = ctx.lang === 'ar';
  const startBox = rtl ? 'right' : 'left';
  const endBox = rtl ? 'left' : 'right';
  const style = `font-family: ${FONT_STACK}; font-size: 10.5px; color: #4A5856; vertical-align: top; padding-top: 3mm;`;
  const rules: string[] = [];
  if (doc.marginFooter !== false) {
    rules.push(`@bottom-${startBox} { content: "${cssString(printedByText(ctx))}"; ${style} width: 40%; text-align: ${rtl ? 'right' : 'left'}; }`);
    rules.push(`@bottom-center { content: "${cssString(generatedText(ctx))}"; ${style} width: 40%; text-align: center; }`);
  }
  if (doc.pageNumbers) {
    const counter = rtl ? 'arabic-indic' : 'decimal';
    rules.push(`@bottom-${endBox} { content: "${cssString(pick(ctx, 'صفحة', 'Page'))} " counter(page, ${counter}) " ${cssString(pick(ctx, 'من', 'of'))} " counter(pages, ${counter}); ${style} width: 20%; text-align: ${rtl ? 'left' : 'right'}; }`);
  }
  return rules.length ? `@page { ${rules.join(' ')} }` : '';
}

// ---------------------------------------------------------------- marks

/** "نسخة" with the reprint time, on a reprinted document. */
export function copyMark(ctx: PrintContext): string {
  if (!ctx.copy) return '';
  const when = `${formatDate(ctx.copy.at, ctx.lang)} ${formatTime(ctx.copy.at, ctx.lang)}`;
  const copyNo = ctx.copy.n > 1 ? ` ${localizeDigits(String(ctx.copy.n), ctx.lang)}` : '';
  return `<div class="copy-mark" data-copy-mark>${pick(ctx, 'نسخة', 'COPY')}${copyNo}<small>${pick(ctx, 'أُعيدت الطباعة', 'Reprinted')} ${escapeHtml(when)}</small></div>`;
}

function watermark(ctx: PrintContext, doc: PrintDocument): string {
  if (!doc.cancelled) return '';
  const reason = doc.cancelled.reason ? `<small>${escapeHtml(doc.cancelled.reason)}</small>` : '';
  return `<div class="watermark" data-cancelled-watermark>${pick(ctx, 'ملغي', 'CANCELLED')}${reason}</div>`;
}

/** The cancel reason line under the title of a cancelled document. */
export function cancelBox(ctx: PrintContext, cancelled: { reason?: string | null; at?: string | Date | null; by?: string | null } | null | undefined): string {
  if (!cancelled) return '';
  const parts = [pick(ctx, 'ملغي', 'Cancelled')];
  if (cancelled.at) parts.push(formatDate(cancelled.at, ctx.lang));
  if (cancelled.by) parts.push(escapeHtml(cancelled.by));
  const reason = cancelled.reason ? `<div style="font-weight:500; margin-top:2px">${pick(ctx, 'السبب', 'Reason')}: ${escapeHtml(cancelled.reason)}</div>` : '';
  return `<div class="cancel-box keep" data-cancel-reason>${parts.join(' · ')}${reason}</div>`;
}

// ---------------------------------------------------------------- the document

/**
 * The complete HTML document. `heightMm` only matters for 80mm rolls: the page is as tall as the receipt
 * (the renderer measures it first, see PrintService). Everything is inline: no network, no external CSS.
 */
export function buildPrintHtml(ctx: PrintContext, doc: PrintDocument, heightMm = 297): string {
  const dir = ctx.lang === 'ar' ? 'rtl' : 'ltr';
  const pageRule = doc.paper === '80mm' ? `@page { size: 80mm ${Math.max(40, Math.ceil(heightMm))}mm; margin: 0; }` : PAGE_RULES[doc.paper];
  const boxes = doc.paper === 'A4' ? marginBoxes(ctx, doc) : '';
  return `<!doctype html>
<html lang="${ctx.lang}" dir="${dir}">
<head>
<meta charset="utf-8">
<meta http-equiv="Content-Security-Policy" content="default-src 'none'; style-src 'unsafe-inline'; font-src data:; img-src data:">
<title>${escapeHtml(doc.title)}</title>
<style>
${ctx.fontCss || ''}
${BASE_CSS}
${RECEIPT_CSS}
${A5_CSS}
${pageRule}
${boxes}
</style>
</head>
<body data-paper="${doc.paper}">
${watermark(ctx, doc)}
${doc.body}
</body>
</html>`;
}

