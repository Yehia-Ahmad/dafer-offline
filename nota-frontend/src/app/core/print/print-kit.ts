/** The default brand mark is not printed: a shop without a logo gets no logo. */
function logoImg(shop: ShopPrintInfo | null, size: number): string {
  if (!shop || !shop.logo) return '';
  if (!/^(data:image\/(png|jpe?g|webp|gif|svg\+xml);|https?:|file:)/i.test(shop.logo)) return '';
  return `<img src="${escapeHtml(shop.logo)}" alt="" width="${size}" height="${size}" style="width:${size}px;height:${size}px;object-fit:contain;border-radius:10px">`;
}

const phonesText = (shop: ShopPrintInfo | null): string => (shop ? shop.phones.join(' · ') : '');

/** PrHeader: logo + shop details on the start side, the document title and its number/date on the end side, a brand rule below. */
export function a4Header(
  ctx: PrintContext,
  head: { title: string; no?: string; date?: string; extraLabel?: string; extra?: string; extra2Label?: string; extra2?: string }
): string {
  const shop = ctx.shop;
  const details = shop
    ? `<div class="col" style="gap:3px">
        <span style="font-size:20px;font-weight:800">${escapeHtml(shop.name)}</span>
        ${shop.address ? `<span class="muted" style="font-size:12px">${escapeHtml(shop.address)}</span>` : ''}
        ${shop.phones.length ? `<span class="muted n" style="font-size:12px;direction:ltr;text-align:${ctx.lang === 'ar' ? 'right' : 'left'}">${escapeHtml(phonesText(shop))}</span>` : ''}
        ${shop.commercialRegister ? `<span class="muted" style="font-size:12px">${pick(ctx, 'س.ت', 'C.R.')} ${escapeHtml(localizeDigits(shop.commercialRegister, ctx.lang))}</span>` : ''}
        ${shop.taxNumber ? `<span class="muted" style="font-size:12px">${pick(ctx, 'الرقم الضريبي', 'Tax no.')} <span class="ltr">${escapeHtml(shop.taxNumber)}</span></span>` : ''}
      </div>`
    : '';
  const meta: Array<[string, string]> = [];
  if (head.no) meta.push([pick(ctx, 'رقم', 'No.'), `<span class="code" style="font-weight:700">${escapeHtml(head.no)}</span>`]);
  if (head.date) meta.push([pick(ctx, 'التاريخ', 'Date'), `<span style="font-weight:700">${escapeHtml(head.date)}</span>`]);
  if (head.extra) meta.push([head.extraLabel || '', `<span style="font-weight:700">${escapeHtml(head.extra)}</span>`]);
  if (head.extra2) meta.push([head.extra2Label || '', `<span style="font-weight:700">${escapeHtml(head.extra2)}</span>`]);
  const grid = meta.map(([label, value]) => `<span class="muted">${escapeHtml(label)}</span>${value}`).join('');
  return `<header class="col keep" style="gap:14px" data-header>
  <div class="row" style="justify-content:space-between;align-items:flex-start;gap:20px">
    <div class="row" style="align-items:center;gap:14px">${logoImg(shop, 72)}${details}</div>
    <div class="col" style="align-items:flex-end;gap:6px;text-align:end">
      <span style="font-size:24px;font-weight:800;color:var(--p-brand)" data-title>${escapeHtml(head.title)}</span>
      ${grid ? `<div style="display:grid;grid-template-columns:auto auto;column-gap:12px;row-gap:2px;font-size:12px">${grid}</div>` : ''}
      ${copyMark(ctx)}
    </div>
  </div>
  <div style="height:3px;background:var(--p-brand);border-radius:2px"></div>
</header>`;
}

/** The shop details at the top of an 80mm receipt (PrCashReceipt): logo, name, address, phone, then a dashed rule. */
export function receiptHeader(ctx: PrintContext): string {
  const shop = ctx.shop;
  return `<div class="col head" style="gap:2px" data-header>
    ${logoImg(shop, 56)}
    ${shop ? `<span style="font-size:17px;font-weight:800">${escapeHtml(shop.name)}</span>` : ''}
    ${shop && shop.address ? `<span style="font-size:12px">${escapeHtml(shop.address)}</span>` : ''}
    ${shop && shop.phones.length ? `<span class="n" style="font-size:12px;direction:ltr">${escapeHtml(phonesText(shop))}</span>` : ''}
    ${shop && shop.taxNumber ? `<span style="font-size:12px">${pick(ctx, 'الرقم الضريبي', 'Tax no.')} <span class="ltr">${escapeHtml(shop.taxNumber)}</span></span>` : ''}
  </div>
  <div class="dash"></div>`;
}

/** A label/value row of an 80mm receipt. */
export const receiptRow = (label: string, value: string, extra = ''): string =>
  `<div class="r n"${extra ? ` ${extra}` : ''}><span>${label}</span><span>${value}</span></div>`;

/** The bottom of an 80mm receipt: the shop footer text (sales documents only), "printed by", the generated-by line. */
export function receiptFooter(ctx: PrintContext, noun: 'document' | 'voucher' | 'receipt' = 'document', salesFooter = false): string {
  // The shop's footer ("لا ترد ولا تستبدل") belongs to sales documents only.
  const note = salesFooter && ctx.shop && ctx.shop.invoiceFooter ? `<div class="note" data-footer-note>${escapeHtml(ctx.shop.invoiceFooter)}</div>` : '';
  return `<div class="dash"></div>${note}
  <div class="fine" data-printed-by>${escapeHtml(printedByText(ctx))}</div>
  <div class="fine">${escapeHtml(generatedText(ctx, noun))}</div>`;
}

/** An 80mm page wrapper. */
export const receiptPage = (inner: string): string => `<main class="page80">${inner}</main>`;

/** An A4 page wrapper (the page margins come from @page). */
export const a4Page = (inner: string, gap = 18): string => `<main class="col" style="gap:${gap}px">${inner}</main>`;

/** A table. `head` cells are `{ label, numeric?, width? }`; `rows` are already-built <tr> strings. */
export function table(head: Array<{ label: string; numeric?: boolean; width?: number }>, rows: string, options: { foot?: string; extraClass?: string } = {}): string {
  const th = head.map((cell) => `<th${cell.numeric ? ' class="n"' : ''}${cell.width ? ` style="width:${cell.width}px"` : ''}>${escapeHtml(cell.label)}</th>`).join('');
  return `<table class="t${options.extraClass ? ` ${options.extraClass}` : ''}"><thead><tr>${th}</tr></thead><tbody>${rows}${options.foot || ''}</tbody></table>`;
}

/** A body row: cells are { html, numeric?, code?, bold? } or plain (already escaped) strings. */
export type Cell = string | { html: string; numeric?: boolean; code?: boolean; bold?: boolean; colspan?: number };
export function row(cells: Cell[], className = ''): string {
  const tds = cells
    .map((cell) => {
      if (typeof cell === 'string') return `<td>${cell}</td>`;
      const classes = [cell.numeric ? 'n' : '', cell.code ? 'code-cell' : ''].filter(Boolean).join(' ');
      const style = cell.bold ? ' style="font-weight:700"' : '';
      const inner = cell.code ? `<span class="code">${cell.html}</span>` : cell.html;
      return `<td${classes ? ` class="${classes}"` : ''}${cell.colspan ? ` colspan="${cell.colspan}"` : ''}${style}>${inner}</td>`;
    })
    .join('');
  return `<tr${className ? ` class="${className}"` : ''}>${tds}</tr>`;
}

/** The signature block: two or three columns of "who" + a line. The strings are RAW text (escaped here, once). */
export function signatures(items: Array<{ who: string; line: string }>): string {
  return `<div class="sig keep" style="grid-template-columns:repeat(${items.length}, minmax(0, 1fr))" data-signatures>${items
    .map((item) => `<div><span>${escapeHtml(item.who)}</span><span class="line">${escapeHtml(item.line)}</span></div>`)
    .join('')}</div>`;
}

/** The signature block (and, on sales documents only, the shop's footer text), kept together on the last page. Pass RAW strings: signatures() escapes them, once. */
export function closing(ctx: PrintContext, items: Array<{ who: string; line: string }>, salesFooter = false): string {
  return `<div class="col keep" style="gap:14px" data-closing>${signatures(items)}${salesFooter ? shopNote(ctx) : ''}</div>`;
}

/** The shop's footer text at the end of an A4/A5 document. */
export const shopNote = (ctx: PrintContext): string =>
  ctx.shop && ctx.shop.invoiceFooter ? `<div class="note keep" data-footer-note>${escapeHtml(ctx.shop.invoiceFooter)}</div>` : '';

/** A4 header date/time label used by several documents. */
export const headerDate = (ctx: PrintContext, value: string | Date | null | undefined): string => formatDate(value ?? ctx.printedAt, ctx.lang);
