import { PrintLanguage, cssString, escapeHtml, formatDate, formatDateTime, formatTime, localizeDigits } from './print-format';

export type PrintPaper = '80mm' | 'A4' | 'A5';

/** What the printed header needs of the shop profile. */
export interface ShopPrintInfo {
  name: string;
  address: string;
  phones: string[];
  /** A data: URL or image URL; empty = no logo. */
  logo: string;
  taxNumber: string;
  commercialRegister: string;
  /** The receipt/invoice footer text of the shop profile. */
  invoiceFooter: string;
}

export interface PrintContext {
  lang: PrintLanguage;
  shop: ShopPrintInfo | null;
  /** The signed-in user. */
  printedBy: string;
  printedAt: Date;
  /** `@font-face` rules with the Alexandria files embedded (see PrintFontService); '' falls back to system fonts. */
  fontCss: string;
  /** Set on a reprint (copy 1+): the document shows "نسخة" with this time. */
  copy?: { n: number; at: Date } | null;
}

/** A document ready to be wrapped: the paper and the body HTML. */
export interface PrintDocument {
  paper: PrintPaper;
  /** The window / PDF title (also the suggested file name). */
  title: string;
  body: string;
  /** Cancelled documents carry a "ملغي" watermark on every page. */
  cancelled?: { reason?: string | null } | null;
  /** Multi-page A4: page numbers in the page margin ("صفحة ١ من ٣"). */
  pageNumbers?: boolean;
  /** A4/A5 only: the "printed by" and "generated by" footer in the page margin of every page. */
  marginFooter?: boolean;
}

export function toShopInfo(profile: ShopProfile | null | undefined): ShopPrintInfo | null {
  if (!profile || !profile.name || !profile.name.trim()) return null;
  return {
    name: profile.name.trim(),
    address: (profile.address || '').trim(),
    phones: (profile.phones || []).map((phone) => String(phone).trim()).filter(Boolean),
    logo: toImageSrc(profile.logo),
    taxNumber: (profile.taxNumber || '').trim(),
    commercialRegister: (profile.commercialRegister || '').trim(),
    invoiceFooter: (profile.invoiceFooter || '').trim(),
  };
}

export const pick = (ctx: Pick<PrintContext, 'lang'>, ar: string, en: string): string => (ctx.lang === 'ar' ? ar : en);
export const brandLabel = (ctx: Pick<PrintContext, 'lang'>): string => (ctx.lang === 'ar' ? BRAND.nameAr : BRAND.nameEn);
export const generatedText = (ctx: Pick<PrintContext, 'lang'>, noun: 'document' | 'voucher' | 'receipt' = 'document'): string => {
  const ar = { document: 'تم إنشاء هذا المستند', voucher: 'تم إنشاء السند', receipt: 'تم إنشاء الإيصال' }[noun];
  const en = { document: 'This document was', voucher: 'This voucher was', receipt: 'This receipt was' }[noun];
  return ctx.lang === 'ar' ? `${ar} إلكترونيًا بواسطة ${BRAND.nameAr}` : `${en} generated electronically by ${BRAND.nameEn}`;
};
export const printedByText = (ctx: PrintContext): string =>
  `${pick(ctx, 'طُبع بواسطة', 'Printed by')} ${ctx.printedBy || '—'} · ${formatDateTime(ctx.printedAt, ctx.lang).replace(' · ', ' ')}`;

