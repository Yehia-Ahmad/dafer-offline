#!/usr/bin/env node
// Online Stage Help: generates, from the same data the app shows,
//   1. src/app/help/generated/permission-catalog.ts  (a copy of nota-backend/src/auth/permissions.js: keys, labels, groups,
//      role templates, dependencies; the browser specs cannot read the backend, so they check this copy), and
//   2. docs/help/HELP_AR.md                           (the whole help in one Markdown file, in section order), and
//   3. src/app/help/generated/audit-actions.ts       (every audit action code the backend writes: the audit page's filter and the
//      spec that fails when a code has no Arabic / English label).
// Usage: node scripts/export-help.mjs          write both files
//        node scripts/export-help.mjs --check  write nothing; exit 1 when either file is out of date
import { createRequire } from 'node:module';
import { mkdtempSync, readFileSync, readdirSync, rmSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const frontend = resolve(here, '..');
const repo = resolve(frontend, '..');
const check = process.argv.includes('--check');
const require = createRequire(import.meta.url);

const catalogPath = join(frontend, 'src/app/help/generated/permission-catalog.ts');
const markdownPath = join(repo, 'docs/help/HELP_AR.md');
const auditPath = join(frontend, 'src/app/help/generated/audit-actions.ts');

// 1. The permission catalog, copied from the backend (the single source of truth).
const backend = require(join(repo, 'nota-backend/src/auth/permissions.js'));
const catalog = {
  keys: [...backend.ALL_PERMISSIONS],
  permissions: Object.fromEntries(backend.ALL_PERMISSIONS.map((key) => [key, { group: backend.PERMISSIONS[key].group, ar: backend.PERMISSIONS[key].ar, en: backend.PERMISSIONS[key].en }])),
  groups: Object.fromEntries(Object.entries(backend.PERMISSION_GROUPS).map(([key, value]) => [key, value.ar])),
  roles: Object.fromEntries(Object.entries(backend.ROLE_LABELS).map(([key, value]) => [key, value.ar])),
  groupsEn: Object.fromEntries(Object.entries(backend.PERMISSION_GROUPS).map(([key, value]) => [key, value.en])),
  rolesEn: Object.fromEntries(Object.entries(backend.ROLE_LABELS).map(([key, value]) => [key, value.en])),
  templates: Object.fromEntries(Object.entries(backend.ROLE_TEMPLATES).map(([key, value]) => [key, [...value]])),
  dependencies: Object.fromEntries(Object.entries(backend.PERMISSION_DEPENDENCIES).map(([key, value]) => [key, [...value]])),
};
const catalogSource = [
  '// Generated by scripts/export-help.mjs from nota-backend/src/auth/permissions.js. Do not edit by hand:',
  '// run `node scripts/export-help.mjs` after changing the backend catalog (`--check` fails while this copy is stale).',
  '',
  'export interface HelpPermissionCatalog {',
  '  keys: readonly string[];',
  '  permissions: Readonly<Record<string, { group: string; ar: string; en: string }>>;',
  '  groups: Readonly<Record<string, string>>;',
  '  roles: Readonly<Record<string, string>>;',
  '  groupsEn: Readonly<Record<string, string>>;',
  '  rolesEn: Readonly<Record<string, string>>;',
  '  templates: Readonly<Record<string, readonly string[]>>;',
  '  dependencies: Readonly<Record<string, readonly string[]>>;',
  '}',
  '',
  `export const PERMISSION_CATALOG: HelpPermissionCatalog = ${JSON.stringify(catalog, null, 2)};`,
  '',
].join('\n');

// Every audit action code the backend writes: the string literals of an `action:` expression (so both sides of a ternary) and the first
// argument of auditOnSuccess(...), in nota-backend/src and nota-backend/scripts.
const walkJs = (dir) => readdirSync(dir, { withFileTypes: true }).flatMap((entry) => (entry.isDirectory() ? walkJs(join(dir, entry.name)) : entry.name.endsWith('.js') ? [join(dir, entry.name)] : []));
const codes = new Set();
for (const root of [join(repo, 'nota-backend/src'), join(repo, 'nota-backend/scripts')]) {
  if (!existsSync(root)) continue;
  for (const file of walkJs(root)) {
    const text = readFileSync(file, 'utf8');
    for (const match of text.matchAll(/auditOnSuccess\(\s*["']([a-z_]+(?:\.[a-z_]+)+)["']/g)) codes.add(match[1]);
    for (const line of text.split(/\r?\n/)) {
      const at = line.indexOf('action:');
      if (at < 0) continue;
      const expression = line.slice(at + 'action:'.length).split(/,\s*entity\s*:/)[0];
      for (const match of expression.matchAll(/["']([a-z_]+(?:\.[a-z_]+)+)["']/g)) codes.add(match[1]);
    }
  }
}
const auditSource = [
  '// Generated by scripts/export-help.mjs from every audit action code the backend writes (nota-backend/src and scripts).',
  '// Do not edit by hand: run `node scripts/export-help.mjs` after adding an audit action (`--check` fails while this copy is stale).',
  '',
  `export const BACKEND_AUDIT_ACTIONS: readonly string[] = ${JSON.stringify([...codes].sort(), null, 2)};`,
  '',
].join('\n');

let stale = [];
const current = (path) => (existsSync(path) ? readFileSync(path, 'utf8').replace(/\r\n/g, '\n') : null);

if (current(catalogPath) !== catalogSource) {
  if (check) stale.push(catalogPath);
  else { mkdirSync(dirname(catalogPath), { recursive: true }); writeFileSync(catalogPath, catalogSource); }
}

if (current(auditPath) !== auditSource) {
  if (check) stale.push(auditPath);
  else { mkdirSync(dirname(auditPath), { recursive: true }); writeFileSync(auditPath, auditSource); }
}

// 2. The Markdown: bundle the TS content + helpToMarkdown with esbuild (installed with the Angular build tools) and run it.
const esbuild = require('esbuild');
const work = mkdtempSync(join(tmpdir(), 'nota-help-'));
try {
  const outfile = join(work, 'export.mjs');
  await esbuild.build({
    entryPoints: [join(frontend, 'src/app/help/export/markdown.entry.ts')],
    bundle: true,
    platform: 'node',
    format: 'esm',
    outfile,
    logLevel: 'error',
    // When checking, the content must be read with the catalog the backend has now, not the stale copy.
    plugins: check ? [{
      name: 'fresh-catalog',
      setup(build) {
        build.onLoad({ filter: /permission-catalog\.ts$/ }, () => ({ contents: catalogSource, loader: 'ts' }));
      },
    }] : [],
  });
  const { renderHelpMarkdown } = await import(pathToFileURL(outfile).href);
  const markdown = renderHelpMarkdown();
  if (current(markdownPath) !== markdown) {
    if (check) stale.push(markdownPath);
    else { mkdirSync(dirname(markdownPath), { recursive: true }); writeFileSync(markdownPath, markdown); }
  }
} finally {
  rmSync(work, { recursive: true, force: true });
}

if (check) {
  if (stale.length) {
    console.error(`Out of date (run node scripts/export-help.mjs):\n${stale.map((path) => `  ${path}`).join('\n')}`);
    process.exit(1);
  }
  console.log('Help export is up to date.');
} else {
  console.log(`Wrote ${catalogPath}\nWrote ${auditPath}\nWrote ${markdownPath}`);
}
